const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async()=>{
  const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.route('https://fonts.googleapis.com/**',route=>route.abort());
    const home=pathToFileURL(path.resolve('index.html')).href;
    await page.goto(home);
    const catalog=await page.evaluate(()=>window.FOLIO_TEMPLATES);
    assert.equal(await page.locator('.home-template').count(),catalog.length);
    assert(await page.locator('.hero-image').evaluate(img=>img.complete&&img.naturalWidth>0));
    await page.locator('[data-filter=student]').click();
    assert.equal(await page.locator('.home-template:visible').count(),catalog.filter(template=>template.group==='student').length);
    await page.locator('[data-filter=all]').click();
    await page.screenshot({path:'home-desktop.png',fullPage:true});
    await page.getByRole('link',{name:'Use Canvas template',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#cv-preview')?.classList.contains('creative'));
    assert((await page.locator('#cv-preview').getAttribute('class')).includes('creative'));
    await page.locator('[name=name]').fill('Photo Test');
    await page.locator('#photo-input').setInputFiles(path.resolve('assets/owner.png'));
    await page.waitForFunction(()=>!document.querySelector('#apply-photo').disabled);
    assert(await page.locator('#photo-dialog').isVisible());
    assert.equal(await page.locator('.cv-photo').count(),0);
    await page.locator('#crop-zoom').fill('0.6');
    await page.locator('[data-photo-action=rotate]').click();
    await page.locator('[data-photo-action=flip]').click();
    await page.locator('#crop-brightness').fill('115');
    await page.locator('#crop-contrast').fill('108');
    const canvas=page.locator('#crop-preview');
    assert(await canvas.evaluate(c=>{const pixels=c.getContext('2d').getImageData(0,0,480,480).data;return pixels.some((value,index)=>index%4!==3&&value>20&&value<240);}));
    await page.screenshot({path:'photo-editor-desktop.png',fullPage:false});
    await page.locator('#apply-photo').click();
    await page.waitForSelector('.cv-photo');
    assert.equal(await page.locator('.cv-photo').evaluate(img=>img.naturalWidth),480);
    const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('folio-cv-v1')));
    assert.equal(saved.photoEdits.brightness,115);
    assert.equal(saved.photoEdits.rotate,90);
    assert.equal(saved.photoEdits.scaleX,-1);
    assert(saved.photoSource&&saved.photoSource!==saved.photo);
    const applied=await page.locator('.cv-photo').getAttribute('src');
    await page.reload();
    await page.locator('#adjust-photo').click();
    await page.waitForFunction(()=>!document.querySelector('#apply-photo').disabled);
    assert.equal(await page.locator('#crop-brightness').inputValue(),'115');
    await page.locator('[data-photo-action=reset]').click();
    await page.locator('#cancel-photo').click();
    assert.equal(await page.locator('.cv-photo').getAttribute('src'),applied);
    await page.setViewportSize({width:390,height:844});
    await page.locator('#adjust-photo').click();
    await page.waitForFunction(()=>!document.querySelector('#apply-photo').disabled);
    assert(await page.locator('#photo-dialog').evaluate(el=>el.scrollWidth<=el.clientWidth));
    await page.screenshot({path:'photo-editor-mobile.png'});
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#photo-dialog').isVisible(),false);
    await page.locator('#photo-input').setInputFiles({name:'bad.png',mimeType:'image/png',buffer:Buffer.from('not an image')});
    await page.waitForFunction(()=>document.querySelector('#photo-status').textContent.includes('could not'));
    assert.equal(await page.locator('.cv-photo').getAttribute('src'),applied);
    await page.goto(home);
    assert((await page.locator('#start-building').textContent()).includes('Continue'));
    for(const width of [320,390,768,1440,1920]){
      await page.setViewportSize({width,height:900});
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Overflow at ${width}`);
    }
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'home-mobile.png',fullPage:true});
    await page.locator('#start-building').click();
    await page.waitForFunction(()=>document.querySelector('[name=name]')?.value==='Photo Test');
    assert.equal(await page.locator('[name=name]').inputValue(),'Photo Test');
    await page.emulateMedia({media:'print'});
    assert.equal(await page.locator('#photo-dialog').isVisible(),false);
    await page.pdf({path:'cv-photo-sample.pdf',format:'A4',printBackground:true});
    assert.deepEqual(errors,[]);
    console.log('PASS: home navigation, template filters, image loading, crop/zoom/rotation/flip/lighting, original retention, cancel, reload, corrupt uploads, mobile layouts, and PDF.');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
